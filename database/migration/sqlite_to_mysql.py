#!/usr/bin/env python3
"""
Repeatable, non-destructive data migration: original Prisma/SQLite database -> MySQL.

    python3 sqlite_to_mysql.py /path/to/custom.db  > migrate.sql
    mysql -h ... -u root -p stayease < migrate.sql

* The SQLite file is opened READ-ONLY and never modified (take a copy first anyway).
* The output is plain SQL made of upserts (INSERT ... ON DUPLICATE KEY UPDATE) inside one
  transaction, so running it twice is safe and a failure leaves MySQL untouched.
* Conversions: "YYYY-MM-DD" strings -> DATE (validated), Prisma DateTime (epoch milliseconds
  or ISO text) -> UTC DATETIME(3), Boolean -> 0/1.
* Rows that cannot be converted are NOT skipped silently: the script stops with an error.

Verification (compare row counts and totals between the two databases):

    python3 sqlite_to_mysql.py --counts /path/to/custom.db
    mysql ... -e "SELECT COUNT(*), COALESCE(SUM(totalPrice),0) FROM Booking; SELECT COUNT(*) FROM Room;"
"""
import datetime as dt
import re
import sqlite3
import sys

ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def q(value):
    """SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value).replace("\\", "\\\\").replace("'", "''")
    return "'" + text + "'"


def to_date(value, what):
    if not isinstance(value, str) or not ISO_DATE.match(value):
        raise SystemExit(f"{what}: not a YYYY-MM-DD date: {value!r}")
    dt.date.fromisoformat(value)  # raises on impossible dates
    return value


def to_datetime_utc(value, what):
    """Prisma stores DateTime in SQLite as epoch milliseconds (integer) or as ISO-8601 text."""
    if isinstance(value, (int, float)):
        moment = dt.datetime.fromtimestamp(value / 1000.0, tz=dt.timezone.utc)
    elif isinstance(value, str):
        text = value.strip().replace("Z", "+00:00")
        if re.fullmatch(r"-?\d+(\.\d+)?", text):
            moment = dt.datetime.fromtimestamp(float(text) / 1000.0, tz=dt.timezone.utc)
        else:
            moment = dt.datetime.fromisoformat(text)
            if moment.tzinfo is None:
                moment = moment.replace(tzinfo=dt.timezone.utc)
    else:
        raise SystemExit(f"{what}: cannot read DateTime {value!r}")
    return moment.astimezone(dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]


def main(argv):
    counts_only = "--counts" in argv
    paths = [a for a in argv[1:] if not a.startswith("--")]
    if len(paths) != 1:
        raise SystemExit(__doc__)
    con = sqlite3.connect(f"file:{paths[0]}?mode=ro", uri=True)
    con.row_factory = sqlite3.Row

    rooms = con.execute("SELECT * FROM Room ORDER BY id").fetchall()
    bookings = con.execute("SELECT * FROM Booking ORDER BY id").fetchall()

    if counts_only:
        total = sum(b["totalPrice"] for b in bookings)
        print(f"Room rows: {len(rooms)}\nBooking rows: {len(bookings)}\nBooking totalPrice sum: {total}")
        return

    out = ["-- Generated by sqlite_to_mysql.py - upserts, safe to re-run", "SET NAMES utf8mb4;", "START TRANSACTION;"]
    for r in rooms:
        out.append(
            "INSERT INTO `Room` (id, name, description, price, capacity, facilities, features, image, available) "
            f"VALUES ({q(r['id'])}, {q(r['name'])}, {q(r['description'])}, {q(r['price'])}, {q(r['capacity'])}, "
            f"{q(r['facilities'])}, {q(r['features'])}, {q(r['image'])}, {q(1 if r['available'] else 0)}) "
            "ON DUPLICATE KEY UPDATE name=VALUES(name), description=VALUES(description), price=VALUES(price), "
            "capacity=VALUES(capacity), facilities=VALUES(facilities), features=VALUES(features), "
            "image=VALUES(image), available=VALUES(available);"
        )
    for b in bookings:
        ref = b["bookingRef"]
        out.append(
            "INSERT INTO `Booking` (id, bookingRef, guestName, email, mobile, roomId, checkIn, checkOut, guests, "
            "nights, totalPrice, status, createdAt) VALUES ("
            f"{q(b['id'])}, {q(ref)}, {q(b['guestName'])}, {q(b['email'])}, {q(b['mobile'])}, {q(b['roomId'])}, "
            f"{q(to_date(b['checkIn'], ref + ' checkIn'))}, {q(to_date(b['checkOut'], ref + ' checkOut'))}, "
            f"{q(b['guests'])}, {q(b['nights'])}, {q(b['totalPrice'])}, {q(b['status'])}, "
            f"{q(to_datetime_utc(b['createdAt'], ref + ' createdAt'))}) "
            "ON DUPLICATE KEY UPDATE guestName=VALUES(guestName), email=VALUES(email), mobile=VALUES(mobile), "
            "roomId=VALUES(roomId), checkIn=VALUES(checkIn), checkOut=VALUES(checkOut), guests=VALUES(guests), "
            "nights=VALUES(nights), totalPrice=VALUES(totalPrice), status=VALUES(status), createdAt=VALUES(createdAt);"
        )
    out += ["COMMIT;", f"-- {len(rooms)} rooms, {len(bookings)} bookings"]
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write(f"Prepared {len(rooms)} rooms and {len(bookings)} bookings.\n")


if __name__ == "__main__":
    main(sys.argv)
